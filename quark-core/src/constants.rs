//! Константы Skhoron-Quark.
//!
//! ⚠️ СТАТУС: ПРЕДВАРИТЕЛЬНЫЕ ЗНАЧЕНИЯ.
//! Ротационные константы ниже выбраны по формальным критериям (см. ниже),
//! но НЕ прошли автоматизированный поиск лучшего differential trail
//! (MILP/SAT, см. analysis/differential_search.py). Количество раундов
//! — временная оценка с запасом, а не результат анализа.
//! Перед любым использованием вне учебных целей нужно прогнать анализ
//! из папки `analysis/` и при необходимости скорректировать эти значения.

/// Размер блока в 32-битных словах (256 бит = 8 слов).
pub const WORDS: usize = 8;

/// Ротационные константы, по одной на каждое из 8 слов состояния.
///
/// Критерии подбора:
///   1. Ни одна константа НЕ кратна 8 (избегаем выравнивания на байтовые
///      границы — иначе часть диффузии сводится к перестановке байтов,
///      что упрощает анализ атакующему).
///   2. Все значения взаимно просты с 32, чтобы избежать периодических
///      паттернов при накоплении ротаций по раундам.
///   3. Значения различны для каждой позиции (асимметрия), чтобы не
///      создавать симметрию между словами, которую можно использовать
///      в slide-атаках.
///   4. Значения распределены по диапазону [1, 31], избегая кластеризации.
pub const ROTATIONS: [u32; WORDS] = [7, 13, 17, 23, 3, 29, 11, 19];

/// Количество раундов шифрования.
///
/// ПРЕДВАРИТЕЛЬНО: 24. Обоснование (временное, до формального анализа):
///   - ChaCha20 использует security margin ~3x над лучшей известной атакой
///     (атаки доходят до ~7 из 20 раундов).
///   - До проведения дифференциального/линейного анализа именно для
///     структуры Quark (Sum → Cross-XOR → Rotation) нельзя утверждать,
///     что 24 раунда дают эквивалентный запас прочности.
///   - См. docs/DESIGN_RATIONALE.md и analysis/differential_search.py —
///     финальное число раундов должно быть пересмотрено по результатам
///     автоматизированного поиска лучшего trail.
pub const ROUNDS: usize = 24;

/// Константа приращения для расписания ключей (дробная часть золотого
/// сечения в 32-битном представлении, стандартная техника Weyl-последовательности,
/// используется, например, в TEA/XTEA для генерации раундовых констант).
pub const KEY_SCHEDULE_INCREMENT: u32 = 0x9E37_79B9;