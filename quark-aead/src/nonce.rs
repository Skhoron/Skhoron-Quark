//! Генерация nonce для Skhoron-Quark AEAD.
//!
//! Nonce — 192 бита (24 байта), по аналогии с XChaCha20 — достаточно
//! большой, чтобы генерировать его случайно через OsRng и не заботиться
//! о коллизиях (birthday bound для 192 бит астрономически высок).
//!
//! ⚠️ Nonce НИКОГДА не должен повторяться для одного и того же ключа.
//! При случайной генерации через OsRng вероятность коллизии на 192 битах
//! пренебрежимо мала даже при огромном числе сообщений — именно поэтому
//! выбран такой большой размер вместо, например, 96-битного счётчика,
//! который требовал бы аккуратного управления состоянием счётчика.

use rand::{rngs::OsRng, RngCore};

pub const NONCE_LEN: usize = 24;

/// Генерирует криптостойкий случайный nonce через OsRng.
pub fn generate_nonce() -> [u8; NONCE_LEN] {
    let mut nonce = [0u8; NONCE_LEN];
    OsRng.fill_bytes(&mut nonce);
    nonce
}